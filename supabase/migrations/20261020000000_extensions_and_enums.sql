-- =====================================================================
-- FixLink Ethiopia — 001: extensions, enums, shared triggers
-- =====================================================================
-- This migration is the foundation for every other migration in the
-- project. It must be applied first.
--
-- Design notes
--  * Supabase Auth is the single authentication system. The database
--    never authenticates users itself; it only trusts the JWT that
--    Supabase Auth signs and that Supabase PostgREST forwards as
--    `request.jwt.claims`.
--  * All ids are UUIDs generated by PostgreSQL (pgcrypto / gen_random_uuid).
--  * Enum values mirror `packages/shared-types/src/roles.ts` and
--    `packages/shared-types/src/statuses.ts` exactly.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Extensions
-- ---------------------------------------------------------------------
create extension if not exists pgcrypto with schema extensions;
create extension if not exists postgis with schema extensions;

-- `gen_random_uuid()` lives in pgcrypto for older PostgreSQL versions.
-- PostgreSQL 13+ has it in core, so make sure it is always reachable.
create schema if not exists extensions;

-- ---------------------------------------------------------------------
-- Enums — keep in sync with packages/shared-types/src/roles.ts
-- ---------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_type where typname = 'user_role') then
    create type public.user_role as enum ('customer', 'professional', 'admin');
  end if;

  if not exists (select 1 from pg_type where typname = 'account_status') then
    create type public.account_status as enum ('active', 'suspended', 'closed');
  end if;

  if not exists (select 1 from pg_type where typname = 'verification_status') then
    create type public.verification_status as enum ('pending', 'approved', 'rejected');
  end if;

  if not exists (select 1 from pg_type where typname = 'language_code') then
    create type public.language_code as enum ('en', 'am', 'om');
  end if;
end
$$;

